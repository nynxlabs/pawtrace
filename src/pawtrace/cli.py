def cmd_init(args: argparse.Namespace) -> int:
    root = Path(args.dir).resolve()
    cfg_path = root / CONFIG_NAME
    if cfg_path.exists():
        raise CliError(f"{cfg_path} already exists")
    if args.profile not in mod.PROFILES:
        raise CliError(f"unknown profile {args.profile!r} (known: {', '.join(mod.PROFILES)})")
    root.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(
        f"# pawtrace project config — the record of which checks were on.\n"
        f"pawtrace: 1\n"
        f"name: {args.name or root.name}\n"
        f"profile: {args.profile}   # minimal | standard | strict\n"
        f"modules: {{}}   # per-module overrides on top of the profile, e.g. sensitivity: true\n"
        f"paths:\n"
        f"  papers: papers\n"
        f"  runs: runs          # gitignore this\n"
        f"  status: STATUS.md   # generated by `pawtrace status --write`\n"
        f"  images: figures\n"
        f"  vars: {{}}          # ${{name}} substitutions for paths\n"
    )
    created = [str(cfg_path)]
    if args.paper:
        created += _paper_skeleton(root / "papers" / args.paper, args.paper)
    gi = root / ".gitignore"
    if not gi.exists() or "runs/" not in gi.read_text():
        with gi.open("a") as fh:
            fh.write("runs/\n")
    _emit(args, {"created": created}, "created:\n" + "\n".join(f"  {c}" for c in created) + "\nnext: `pawtrace playbook intake`")
    return 0


def _paper_skeleton(d: Path, paper: str) -> list[str]:
    if (d / "spec.yaml").exists():
        raise CliError(f"{d / 'spec.yaml'} already exists")
    (d / "panels").mkdir(parents=True, exist_ok=True)
    created = []
    for name in ("spec.yaml", "ledger.yaml"):
        src = resources.files("pawtrace") / "templates" / name
        (d / name).write_text(src.read_text().replace("<paper-id>", paper))
        created.append(str(d / name))
    src = resources.files("pawtrace") / "templates" / "panel.yaml"
    (d / "panels" / "example.yaml").write_text(src.read_text())
    created.append(str(d / "panels" / "example.yaml"))
    return created


def cmd_add_paper(args: argparse.Namespace) -> int:
    proj = _project(args)
    created = _paper_skeleton(proj.paper_dir(args.paper), args.paper)
    _emit(args, {"created": created}, "created:\n" + "\n".join(f"  {c}" for c in created)
          + f"\nnext: fill spec.yaml (`pawtrace playbook intake`), then `pawtrace lint {args.paper}`")
    return 0


def cmd_modules(args: argparse.Namespace) -> int:
    proj = _project(args)
    if args.action in ("enable", "disable"):
        if not args.name:
            raise CliError(f"modules {args.action} needs a module name")
        if args.name not in mod.MODULES:
            raise mod.ModuleError(f"unknown module {args.name!r} (`pawtrace modules` lists them)")
        names = mod.with_dependencies(args.name) if (args.action == "enable" and args.with_deps) else [args.name]
        for n in names:
            if not mod.MODULES[n].core:
                proj.set_module(n, args.action == "enable")
    state = proj.modules()
    missing = mod.missing_dependencies(state)
    rows = [
        {
            "module": m.name,
            "group": m.group,
            "on": state[m.name],
            "core": m.core,
            "implemented": m.implemented,
            "depends": list(m.depends),
            "summary": m.summary,
        }
        for m in mod.MODULES.values()
    ]
    lines = [f"profile: {proj.profile}"]
    for r in rows:
        flag = "core" if r["core"] else ("on  " if r["on"] else "off ")
        todo = "" if r["implemented"] else "  (not built yet)"
        dep = f"  needs {', '.join(r['depends'])}" if r["depends"] else ""
        lines.append(f"  [{flag}] {r['module']:<20} {r['summary']}{dep}{todo}")
    for m, miss in missing.items():
        lines.append(f"warning: {m} needs {', '.join(miss)} — `pawtrace modules enable {m} --with-deps`")
    _emit(args, {"profile": proj.profile, "modules": rows, "missing_dependencies": missing}, "\n".join(lines))
    return 1 if missing else 0


def cmd_lint(args: argparse.Namespace) -> int:
    proj = _project(args)
    problems: list[dict[str, str]] = []
    papers = [args.paper] if args.paper else proj.papers()
    for p in papers:
        problems += Paper(p, proj.paper_dir(p)).lint()
        for pid in proj.panel_ids(p):
            try:
                problems += Panel.load(proj, pid).lint()
            except (PanelError, ProjectError, yaml.YAMLError) as exc:
                problems.append({"level": "error", "panel": pid, "message": str(exc)})
    missing = mod.missing_dependencies(proj.modules())
    for m, miss in missing.items():
        problems.append({"level": "error", "project": proj.name, "message": f"module {m} needs {', '.join(miss)}"})
    for m, on in proj.modules().items():
        if on and not mod.MODULES[m].implemented:
            problems.append({"level": "warn", "project": proj.name, "message": f"module {m} is on but not built yet in pawtrace {__version__}"})
    errors = sum(p["level"] == "error" for p in problems)
    text = "\n".join(f"{p['level']:5} {p.get('panel') or p.get('paper') or p.get('project')}: {p['message']}" for p in problems)
    _emit(args, {"problems": problems, "errors": errors}, text or "no problems")
    return 1 if errors else 0


def cmd_spec(args: argparse.Namespace) -> int:
    proj = _project(args)
    paper = Paper(args.paper, proj.paper_dir(args.paper))
    if not paper.spec:
        raise CliError(f"no spec.yaml for {args.paper} under {proj.papers_dir}")
    if args.action == "render":
        md = paper.render_markdown()
        if args.write:
            out = proj.paper_dir(args.paper) / "SPEC.md"
            out.write_text(md)
            _emit(args, {"wrote": str(out)}, f"wrote {out}")
        else:
            _emit(args, {"markdown": md}, md)
    else:
        s = paper.summary()
        text = (
            f"{s['paper']}: {s['title'] or ''}\n  {s['items']} items: "
            + ", ".join(f"{v} {k}" for k, v in s["items_by_status"].items())
            + f"\n  ledger: {s['ledger_entries']} entries; adopted deviations: {', '.join(s['deviations_adopted']) or 'none'}"
            + f"\n  open gaps: {', '.join(s['open_items']) or 'none'}"
            + f"\n  open author questions: {', '.join(s['open_questions']) or 'none'}"
        )
        _emit(args, s, text)
    return 0


def cmd_panels(args: argparse.Namespace) -> int:
    proj = _project(args)
    store = RunStore(proj.runs_dir)
    rows = []
    for pid in proj.panel_ids():
        rec = store.latest(pid)
        rep = last_report(rec) if rec else None
        try:
            title = Panel.load(proj, pid).title
        except Exception as exc:  # noqa: BLE001
            title = f"(error: {exc})"
        rows.append({"panel": pid, "title": title, "runs": len(store.list(pid)), "latest": rec["id"] if rec else None, "pass": rep["pass"] if rep else None})
    text = "\n".join(
        f"  {r['panel']:<16} {('PASS' if r['pass'] else 'FAIL') if r['pass'] is not None else '—':<5} runs={r['runs']:<3} {r['title']}" for r in rows
    )
    _emit(args, {"panels": rows}, text or "no panels")
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    proj = _project(args)
    panel = Panel.load(proj, args.panel)
    store = RunStore(proj.runs_dir)
    seeds = args.seed or panel.seeds()
    git = git_state(proj.root)
    out = []
    worst = 0
    for seed in seeds:
        t0 = time.time()
        data, config = panel.run(args.config, seed, _parse_sets(args.set))
        rec = store.record_run(panel.id, data, seed=seed, config_name=args.config or panel.default_config_name(), config=config, git=git, elapsed_s=time.time() - t0)
        rep = panel.check(data)
        store.add_check(rec, rep)
        out.append({"run": rec["id"], "seed": seed, "report": rep.to_json()})
        worst = max(worst, 0 if rep.passed else 1)
    _emit(args, {"panel": panel.id, "runs": out}, "\n".join(_fmt_report(panel.id, o["run"], o["report"]) for o in out))
    return worst


def cmd_import(args: argparse.Namespace) -> int:
    proj = _project(args)
    panel = Panel.load(proj, args.panel)
    store = RunStore(proj.runs_dir)
    out = []
    worst = 0
    for f in args.files:
        data, info = panel.import_artifact(f)
        rec = store.record_import(panel.id, data, source=Path(f).resolve(), info=info)
        row: dict[str, Any] = {"run": rec["id"], "from": str(f), "seed": rec.get("seed")}
        if not args.no_check:
            rep = panel.check(data)
            store.add_check(rec, rep)
            row["report"] = rep.to_json()
            worst = max(worst, 0 if rep.passed else 1)
        out.append(row)
    text = "\n".join(
        (_fmt_report(panel.id, r["run"], r["report"]) if "report" in r else f"imported {r['from']} -> {r['run']}") for r in out
    )
    _emit(args, {"panel": panel.id, "imported": out}, text)
    return worst


def cmd_check(args: argparse.Namespace) -> int:
    proj = _project(args)
    panel = Panel.load(proj, args.panel)
    store = RunStore(proj.runs_dir)
    targets: list[tuple[str, PanelData, dict[str, Any] | None]] = []
    if args.data:
        if panel.cfg.get("import") and not args.data.endswith(".panel.json"):
            data, _ = panel.import_artifact(args.data)
        else:
            data = PanelData.load(args.data)
        targets.append((f"file:{args.data}", data, None))
    else:
        recs = store.list(panel.id) if args.all else [store.load(panel.id, args.run)] if args.run else [store.latest(panel.id)]
        recs = [r for r in recs if r]
        if not recs:
            raise CliError(f"no runs for {panel.id} — `pawtrace run` or `pawtrace import` first")
        targets += [(r["id"], PanelData.from_json(r["data"]), r) for r in recs]
    out = []
    worst = 0
    for rid, data, rec in targets:
        rep = panel.check(data)
        if rec is not None and not args.no_save:
            store.add_check(rec, rep)
        out.append({"run": rid, "report": rep.to_json()})
        worst = max(worst, 0 if rep.passed else 1)
    if args.all:
        n_pass = sum(o["report"]["pass"] for o in out)
        per_gate: dict[str, int] = {}
        for o in out:
            for g, r in o["report"]["gates"].items():
                per_gate[g] = per_gate.get(g, 0) + int(r["pass"])
        summary = {"runs": len(out), "pass": n_pass, "per_gate_pass": per_gate}
        text = f"{panel.id}: {n_pass}/{len(out)} runs pass\n" + "\n".join(f"  {g:<36} {c}/{len(out)}" for g, c in per_gate.items())
        _emit(args, {"panel": panel.id, "summary": summary, "runs": out}, text)
    else:
        _emit(args, {"panel": panel.id, "runs": out}, "\n".join(_fmt_report(panel.id, o["run"], o["report"]) for o in out))
    return worst


def cmd_runs(args: argparse.Namespace) -> int:
    proj = _project(args)
    pid = proj.resolve_panel_id(args.panel)
    rows = []
    for r in RunStore(proj.runs_dir).list(pid):
        rep = last_report(r)
        rows.append({
            "run": r["id"], "source": r["source"], "seed": r.get("seed"), "config": r.get("config_name"),
            "created_at": r.get("created_at"), "pass": rep["pass"] if rep else None,
            "gates": f"{rep['n_passed']}/{rep['n_required']}" if rep else None,
            "from": r.get("imported_from"),
        })
    text = "\n".join(
        f"  {r['run']:<34} {r['source']:<6} seed={r['seed']} {('PASS' if r['pass'] else 'FAIL') if r['pass'] is not None else '—'} {r['gates'] or ''}"
        for r in rows
    )
    _emit(args, {"panel": pid, "runs": rows}, text or "no runs")
    return 0


def cmd_overlay(args: argparse.Namespace) -> int:
    from .overlay import next_versioned, plot_panel

    proj = _project(args)
    panel = Panel.load(proj, args.panel)
    store = RunStore(proj.runs_dir)
    rec = store.load(panel.id, args.run) if args.run else store.latest(panel.id)
    if not rec:
        raise CliError(f"no runs for {panel.id}")
    data = PanelData.from_json(rec["data"])
    if args.out:
        out = Path(args.out)
    else:
        out, _ = next_versioned(proj.images_dir / panel.paper / panel.id.split("/", 1)[1], "replication")
    info = plot_panel(panel, data, out, report=last_report(rec))
    info["run"] = rec["id"]
    _emit(args, info, f"wrote {info['out']} (run {rec['id']})" + "".join(f"\nwarning: {w}" for w in info.get("warnings", [])))
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    from . import status

    proj = _project(args)
    if args.write:
        md = status.render(proj)
        proj.status_path.write_text(md)
        _emit(args, {"wrote": str(proj.status_path)}, f"wrote {proj.status_path}")
    else:
        if args.json:
            _emit(args, status.collect(proj), "")
        else:
            print(status.render(proj).rstrip())
    return 0


def cmd_playbook(args: argparse.Namespace) -> int:
    base = resources.files("pawtrace") / "playbooks"
    if not args.stage:
        rows = [{"stage": s, "file": f"{s}.md"} for s in STAGES]
        _emit(args, {"stages": rows}, "stages: " + " → ".join(STAGES) + "\n`pawtrace playbook <stage>` prints one")
        return 0
    if args.stage not in STAGES:
        raise CliError(f"unknown stage {args.stage!r} (stages: {', '.join(STAGES)})")
    text = (base / f"{args.stage}.md").read_text()
    _emit(args, {"stage": args.stage, "markdown": text}, text)
    return 0


def cmd_gates(args: argparse.Namespace) -> int:
    rows = {
        "ops": [{"name": k, "refs": list(v.refs), "doc": v.doc} for k, v in sorted(OPS.items())],
        "checks": [{"name": k, "refs": list(v.refs), "doc": v.doc} for k, v in sorted(CHECKS.items())],
    }
    text = "metric ops:\n" + "\n".join(f"  {r['name']:<18} {r['doc']}" for r in rows["ops"])
    text += "\nchecks:\n" + "\n".join(f"  {r['name']:<18} {r['doc']}" for r in rows["checks"])
    _emit(args, rows, text)
    return 0


