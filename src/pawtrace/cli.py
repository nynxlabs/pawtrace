STAGES = ("intake", "foundations", "gaps", "build", "run", "check", "audit")


class CliError(RuntimeError):
    pass


def _emit(args: argparse.Namespace, obj: Any, text: str) -> None:
    if args.json:
        print(json.dumps(obj, indent=2, default=str))
    else:
        print(text.rstrip())


def _project(args: argparse.Namespace) -> Project:
    return Project.find(args.project) if args.project else Project.find()


def _parse_sets(pairs: list[str]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for p in pairs or []:
        if "=" not in p:
            raise CliError(f"--set needs FIELD=VALUE, got {p!r}")
        k, v = p.split("=", 1)
        out[k] = yaml.safe_load(v)
    return out


def _fmt_report(panel_id: str, rid: str, rep: dict[str, Any]) -> str:
    lines = [f"{panel_id} @ {rid}: {'PASS' if rep['pass'] else 'FAIL'} ({rep['n_passed']}/{rep['n_required']} gates)"]
    for gid, g in rep["gates"].items():
        mark = "ok  " if g["pass"] else "FAIL"
        opt = "" if g.get("required", True) else " (info)"
        detail = ", ".join(f"{k}={_short(v)}" for k, v in g["inputs"].items())
        lines.append(f"  {mark} {gid}{opt}: {g['check']}({detail})" + (f"  error: {g['error']}" if g.get("error") else ""))
    return "\n".join(lines)


def _short(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, list) and len(v) > 4:
        return f"[{len(v)} values]"
    return str(v)


