def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--json", action="store_true", help="machine-readable output")
    common.add_argument("--project", help=f"project dir (default: nearest {CONFIG_NAME} upward)")

    p = argparse.ArgumentParser(prog="pawtrace", description="Rebuild and check published computational research.")
    p.add_argument("--version", action="version", version=f"pawtrace {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("init", parents=[common], help="create pawtrace.yaml (and a paper skeleton with --paper)")
    s.add_argument("dir", nargs="?", default=".")
    s.add_argument("--profile", default="minimal")
    s.add_argument("--name")
    s.add_argument("--paper", help="also scaffold papers/<id>/ spec, ledger and an example panel")
    s.set_defaults(fn=cmd_init)

    s = sub.add_parser("add-paper", parents=[common], help="create papers/<id>/ spec + ledger skeleton in this project (intake starts here)")
    s.add_argument("paper")
    s.set_defaults(fn=cmd_add_paper)

    s = sub.add_parser("modules", parents=[common], help="list modules, or enable/disable one")
    s.add_argument("action", nargs="?", choices=["list", "enable", "disable"], default="list")
    s.add_argument("name", nargs="?")
    s.add_argument("--with-deps", action="store_true", help="enable the module's dependencies too")
    s.set_defaults(fn=cmd_modules)

    s = sub.add_parser("lint", parents=[common], help="check spec, ledger and panel configs")
    s.add_argument("paper", nargs="?")
    s.set_defaults(fn=cmd_lint)

    s = sub.add_parser("spec", parents=[common], help="summarize or render a paper's spec + ledger")
    s.add_argument("action", choices=["show", "render"])
    s.add_argument("paper")
    s.add_argument("--write", action="store_true", help="render: write papers/<id>/SPEC.md")
    s.set_defaults(fn=cmd_spec)

    s = sub.add_parser("panels", parents=[common], help="list panels with their latest verdict")
    s.set_defaults(fn=cmd_panels)

    s = sub.add_parser("run", parents=[common], help="call the panel contract, record the run, check gates")
    s.add_argument("panel")
    s.add_argument("--config", help="named config under run.configs (default: run.default_config / adopted)")
    s.add_argument("--seed", type=int, action="append", help="repeatable (default: run.seeds)")
    s.add_argument("--set", action="append", default=[], metavar="FIELD=VALUE", help="config override (repeatable)")
    s.set_defaults(fn=cmd_run)

    s = sub.add_parser("import", parents=[common], help="record saved artifacts as runs (through the panel's import mapping)")
    s.add_argument("panel")
    s.add_argument("files", nargs="+")
    s.add_argument("--no-check", action="store_true")
    s.set_defaults(fn=cmd_import)

    s = sub.add_parser("check", parents=[common], help="evaluate a panel's gates on a run (default: latest)")
    s.add_argument("panel")
    g = s.add_mutually_exclusive_group()
    g.add_argument("--run", help="run id (prefix ok)")
    g.add_argument("--all", action="store_true", help="every recorded run, with per-gate pass counts")
    g.add_argument("--data", help="check a file directly without recording it")
    s.add_argument("--no-save", action="store_true", help="don't append the result to the run record")
    s.set_defaults(fn=cmd_check)

    s = sub.add_parser("runs", parents=[common], help="list a panel's run records")
    s.add_argument("panel")
    s.set_defaults(fn=cmd_runs)

    s = sub.add_parser("overlay", parents=[common], help="plot a run with its digitized references (versioned PNG)")
    s.add_argument("panel")
    s.add_argument("--run")
    s.add_argument("--out", help="output path (default: <images>/<paper>/<panel>/replication_vN.png)")
    s.set_defaults(fn=cmd_overlay)

    s = sub.add_parser("status", parents=[common], help="generated status page (spec, ledger, panel verdicts)")
    s.add_argument("--write", action="store_true", help="write it to paths.status")
    s.set_defaults(fn=cmd_status)

    s = sub.add_parser("playbook", parents=[common], help="print a stage's agent/person playbook")
    s.add_argument("stage", nargs="?")
    s.set_defaults(fn=cmd_playbook)

    s = sub.add_parser("gates", parents=[common], help="list the gate library's metric ops and checks")
    s.set_defaults(fn=cmd_gates)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.fn(args) or 0)
    except (CliError, ProjectError, PanelError, GateConfigError, mod.ModuleError, FileNotFoundError, yaml.YAMLError) as exc:
        if getattr(args, "json", False):
            print(json.dumps({"error": str(exc), "type": type(exc).__name__}))
        else:
            print(f"pawtrace: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
