"""author-questions module: a template over the ledger's ``questions:``, rendered send-ready.

Each paper's ``ledger.yaml`` holds its author questions (the ledger is core; this module
adds the send-ready view and stricter lint)::

    questions:
      - id: q.example
        question: "…"                   # the text you'd send
        why: "…"                        # why it matters (what it changes)
        items: [param.x]                # spec items it's about (their sections are shown)
        panels: [p1]                    # panels it affects (bare id or paper/panel)
        evidence: ["…"]                 # pointers: runs, overlays, ledger entries, notes
        status: open                    # open | answered-by-us | asked | answered   (legacy: sent = asked)
        asked: 2026-01-01               # when it was sent (asked / answered)
        to: "…"                         # who it went to
        answer: "…"                     # the reply, or how we settled it ourselves
        answer_source: gap.x            # answered-by-us: the ledger entry / source that settled it

``pawtrace questions`` renders the questions grouped by paper (and by panel inside a paper)
as markdown you can paste into an email; by default only the ``open`` ones (not sent yet).
What goes into a question (e.g. parameters only, never code) is the user's policy; the tool
renders what the ledger says and writes no prose of its own. ``--write`` writes the
generated ``QUESTIONS.md`` (``paths.questions``). The ``## author questions`` section of the
generated ``SPEC.md`` uses the same per-question renderer, with every status.
"""
from __future__ import annotations

from typing import Any, Callable

from .spec import Paper

STATUS = ("open", "answered-by-us", "asked", "answered")
ALIASES = {"sent": "asked"}
UNRESOLVED = ("open", "asked")   # still waiting on something
GENERATED = "<!-- generated by `pawtrace questions --write` from each paper's ledger.yaml; do not edit — rerun it instead -->"


def status_of(q: dict[str, Any]) -> str:
    s = str(q.get("status") or "open")
    return ALIASES.get(s, s)


def _list(v: Any) -> list[str]:
    if v is None or v == "":
        return []
    return [str(x) for x in (v if isinstance(v, list) else [v])]


def lint_core(paper: Paper, add: Callable[[str, str], None], item_ids: set[str]) -> None:
    """Always-on checks (the ledger is core): ids, statuses, item references."""
    seen: set[str] = set()
    for q in paper.questions:
        qid = q.get("id")
        if not qid:
            add("error", f"author question without id: {q.get('question')!r}")
            continue
        if qid in seen:
            add("error", f"duplicate question id {qid}")
        seen.add(qid)
        st = str(q.get("status") or "open")
        if st not in STATUS and st not in ALIASES:
            add("error", f"question {qid}: status must be one of {', '.join(STATUS)}")
        if not q.get("question"):
            add("error", f"question {qid}: no question text")
        for it in _list(q.get("items")):
            if it not in item_ids:
                add("error", f"question {qid}: item {it!r} is not in the spec")


def lint_module(paper: Paper, add: Callable[[str, str], None], panel_ids: list[str]) -> None:
    """Extra checks when the author-questions module is on."""
    short = {p.split("/", 1)[1] for p in panel_ids if p.startswith(paper.id + "/")}
    for q in paper.questions:
        qid = q.get("id") or "?"
        st = status_of(q)
        if st == "open" and not q.get("why"):
            add("warn", f"question {qid}: no why (what the answer would change)")
        if st in ("asked", "answered") and not q.get("asked"):
            add("warn", f"question {qid}: {st} but no asked date")
        if st in ("answered", "answered-by-us") and not q.get("answer"):
            add("warn", f"question {qid}: {st} but no answer recorded")
        if st == "answered-by-us" and not q.get("answer_source"):
            add("warn", f"question {qid}: answered-by-us without answer_source (the ledger entry or source that settled it)")
        if not _list(q.get("items")) and not _list(q.get("panels")):
            add("warn", f"question {qid}: names no spec items or panels")
        for p in _list(q.get("panels")):
            bare = p.split("/", 1)[1] if p.startswith(paper.id + "/") else p
            if bare not in short:
                add("error", f"question {qid}: panel {p!r} is not a panel of {paper.id}")


def _sections(paper: Paper) -> dict[str, str]:
    return {str(i.get("id")): str(i.get("section") or "") for i in paper.items if i.get("id")}


def question_lines(paper: Paper, q: dict[str, Any], *, bullet: str, show_status: bool) -> list[str]:
    """One question as markdown: the question line, then indented details."""
    secs = _sections(paper)
    head = f"**{q.get('id')}**" + (f" ({status_of(q)})" if show_status else "")
    lines = [f"{bullet} {head}: {_one_line(q.get('question'))}"]
    pad = " " * (len(bullet) + 1)
    if q.get("why"):
        lines.append(f"{pad}- why it matters: {_one_line(q['why'])}")
    items = [f"{i} ({secs[i]})" if secs.get(i) else i for i in _list(q.get("items"))]
    if items:
        lines.append(f"{pad}- about: {', '.join(items)}")
    panels = _list(q.get("panels"))
    if panels:
        lines.append(f"{pad}- panels: {', '.join(panels)}")
    ev = _list(q.get("evidence"))
    if ev:
        lines.append(f"{pad}- evidence: {'; '.join(_one_line(e) for e in ev)}")
    st = status_of(q)
    if st in ("asked", "answered") and (q.get("asked") or q.get("to")):
        sent = " ".join(x for x in (str(q.get("asked") or ""), f"to {q['to']}" if q.get("to") else "") if x)
        lines.append(f"{pad}- asked: {sent}")
    if q.get("answer") and st in ("answered", "answered-by-us"):
        src = f" ({q['answer_source']})" if q.get("answer_source") else ""
        lines.append(f"{pad}- answer: {_one_line(q['answer'])}{src}")
    return lines


def _one_line(v: Any) -> str:
    return " ".join(str(v or "").split())


def spec_lines(paper: Paper) -> list[str]:
    """The ``## author questions`` body of SPEC.md (every question, with its status)."""
    out: list[str] = []
    for q in paper.questions:
        out += question_lines(paper, q, bullet="-", show_status=True)
    return out


def select(paper: Paper, statuses: tuple[str, ...] | None) -> list[dict[str, Any]]:
    return [q for q in paper.questions if statuses is None or status_of(q) in statuses]


def paper_block(paper: Paper, qs: list[dict[str, Any]], *, show_status: bool) -> list[str]:
    meta = paper.spec.get("paper") or {}
    title = meta.get("title") or paper.id
    authors = meta.get("authors") or []
    who = (authors[0] + (" et al." if len(authors) > 1 else "")) if isinstance(authors, list) and authors else (authors if isinstance(authors, str) else "")
    bits = [b for b in (str(who), str(meta.get("year") or ""), str(meta.get("doi") or "")) if b]
    lines = [f"## {title}" + (f" ({', '.join(bits)})" if bits else ""), ""]
    if meta.get("version"):
        lines += [f"Version read: {meta['version']}", ""]
    by_panel: dict[str, list[dict[str, Any]]] = {}
    for q in qs:
        panels = _list(q.get("panels"))
        key = panels[0].split("/", 1)[-1] if panels else ""
        by_panel.setdefault(key, []).append(q)
    group = any(by_panel.keys() - {""})
    n = 0
    for key in sorted(by_panel, key=lambda k: (k == "", k)):
        if group:
            lines += [f"### {'panel ' + key if key else 'general'}", ""]
        for q in by_panel[key]:
            n += 1
            lines += question_lines(paper, q, bullet=f"{n}.", show_status=show_status)
        lines.append("")
    return lines


def collect(papers: list[Paper], statuses: tuple[str, ...] | None) -> dict[str, Any]:
    rows = []
    for p in papers:
        qs = select(p, statuses)
        asked_items = {i for q in p.questions for i in _list(q.get("items"))}
        rows.append({
            "paper": p.id,
            "title": (p.spec.get("paper") or {}).get("title"),
            "questions": [{**q, "status": status_of(q)} for q in qs],
            "counts": {s: sum(1 for q in p.questions if status_of(q) == s) for s in STATUS},
            "gaps_without_question": [i for i in p.summary()["open_items"] if i not in asked_items],
        })
    return {"statuses": list(statuses) if statuses else None, "papers": rows}


def render(papers: list[Paper], statuses: tuple[str, ...] | None) -> str:
    show_status = statuses is None or len(statuses) > 1
    label = "all" if statuses is None else ", ".join(statuses)
    lines = [GENERATED, "", "# Author questions", "", f"Status: {label}", ""]
    any_q = False
    for p in papers:
        qs = select(p, statuses)
        if not qs:
            continue
        any_q = True
        lines += paper_block(p, qs, show_status=show_status)
    if not any_q:
        lines += ["_No questions._", ""]
    return "\n".join(lines).rstrip() + "\n"
