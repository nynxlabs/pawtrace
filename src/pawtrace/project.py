"""The per-project config (``pawtrace.yaml``) and where a project's files live.

Layout of a project using pawtrace (all plain YAML/markdown, diffable)::

    pawtrace.yaml                 # profile, module toggles, paths — the record of which checks were on
    papers/<paper>/spec.yaml      # every stated / missing detail, with its section; code-use policy
    papers/<paper>/ledger.yaml    # how each gap was filled (source + reason), deviations, author questions
    papers/<paper>/panels/<id>.yaml   # panel contract target, references, metrics, gates, overlay
    runs/                         # run records (gitignored), one JSON per run
    STATUS.md                     # generated by `pawtrace status --write`; never hand-edited

``${name}`` in any path expands from ``paths.vars`` in ``pawtrace.yaml``, then
from the environment (``PAWTRACE_VAR_<NAME>`` or ``<NAME>``); ``~`` expands too.
"""
from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

import yaml

from . import modules as mod

CONFIG_NAME = "pawtrace.yaml"
_VAR = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")


class ProjectError(RuntimeError):
    pass


class Project:
    def __init__(self, root: Path, cfg: dict[str, Any]):
        self.root = root.resolve()
        self.cfg = cfg or {}
        paths = self.cfg.get("paths") or {}
        self.vars: dict[str, str] = {str(k): str(v) for k, v in (paths.get("vars") or {}).items()}
        self.papers_dir = self.path(paths.get("papers", "papers"))
        self.runs_dir = self.path(paths.get("runs", "runs"))
        self.status_path = self.path(paths.get("status", "STATUS.md"))
        self.images_dir = self.path(paths.get("images", "figures"))

    # -- loading ---------------------------------------------------------
    @classmethod
    def find(cls, start: str | Path | None = None) -> "Project":
        here = Path(start or os.getcwd()).resolve()
        if here.is_file():
            here = here.parent
        for d in (here, *here.parents):
            if (d / CONFIG_NAME).is_file():
                return cls.load(d / CONFIG_NAME)
        raise ProjectError(f"no {CONFIG_NAME} in {here} or any parent (run `pawtrace init`)")

    @classmethod
    def load(cls, path: str | Path) -> "Project":
        path = Path(path)
        cfg = yaml.safe_load(path.read_text()) or {}
        if not isinstance(cfg, dict):
            raise ProjectError(f"{path}: expected a mapping")
        return cls(path.parent, cfg)

    @property
    def name(self) -> str:
        return str(self.cfg.get("name") or self.root.name)

    @property
    def config_path(self) -> Path:
        return self.root / CONFIG_NAME

    # -- paths -----------------------------------------------------------
    def expand(self, s: str) -> str:
        def sub(m: re.Match[str]) -> str:
            k = m.group(1)
            if k in self.vars:
                return self.expand(self.vars[k])
            for env in (f"PAWTRACE_VAR_{k.upper()}", k):
                if env in os.environ:
                    return os.environ[env]
            raise ProjectError(f"unknown path variable ${{{k}}} (set paths.vars.{k} in {CONFIG_NAME})")

        return os.path.expanduser(_VAR.sub(sub, str(s)))

    def path(self, p: str | Path) -> Path:
        q = Path(self.expand(str(p)))
        return q if q.is_absolute() else self.root / q

    # -- modules ---------------------------------------------------------
    @property
    def profile(self) -> str:
        return str(self.cfg.get("profile", "minimal"))

    def modules(self) -> dict[str, bool]:
        return mod.resolve(self.profile, self.cfg.get("modules") or {})

    def set_module(self, name: str, on: bool) -> None:
        """Set ``modules.<name>`` in pawtrace.yaml in place (keeps comments)."""
        if name not in mod.MODULES:
            raise mod.ModuleError(f"unknown module {name!r}")
        if mod.MODULES[name].core:
            raise mod.ModuleError(f"{name} is core (always on)")
        lines = self.config_path.read_text().splitlines()
        val = "true" if on else "false"
        start = next((i for i, ln in enumerate(lines) if re.match(r"^modules\s*:", ln)), None)
        if start is None:
            lines += ["", "modules:", f"  {name}: {val}"]
        else:
            m = re.match(r"^modules\s*:\s*(?P<body>[^#]*?)\s*(?P<comment>#.*)?$", lines[start])
            body = (m.group("body") if m else "").strip()
            comment = f"  {m.group('comment')}" if m and m.group("comment") else ""
            if body:  # inline flow mapping, e.g. `modules: {sensitivity: true}` -> block form
                flow = yaml.safe_load(body) or {}
                if not isinstance(flow, dict):
                    raise mod.ModuleError(f"{CONFIG_NAME}: modules must be a mapping")
                lines[start : start + 1] = [f"modules:{comment}"] + [
                    f"  {k}: {'true' if v else 'false'}" for k, v in flow.items()
                ]
            end = start + 1
            while end < len(lines) and (lines[end].startswith((" ", "\t")) or not lines[end].strip()):
                end += 1
            while end > start + 1 and not lines[end - 1].strip():
                end -= 1  # insert before trailing blank lines
            for i in range(start + 1, end):
                hit = re.match(rf"^(\s+){re.escape(name)}\s*:[^#]*(#.*)?$", lines[i])
                if hit:
                    lines[i] = f"{hit.group(1)}{name}: {val}" + (f"  {hit.group(2)}" if hit.group(2) else "")
                    break
            else:
                lines.insert(end, f"  {name}: {val}")
        self.config_path.write_text("\n".join(lines) + "\n")
        self.cfg = yaml.safe_load(self.config_path.read_text()) or {}

    # -- papers and panels -------------------------------------------------
    def papers(self) -> list[str]:
        if not self.papers_dir.is_dir():
            return []
        return sorted(p.name for p in self.papers_dir.iterdir() if (p / "spec.yaml").is_file() or (p / "panels").is_dir())

    def paper_dir(self, paper: str) -> Path:
        return self.papers_dir / paper

    def panel_ids(self, paper: str | None = None) -> list[str]:
        out: list[str] = []
        for p in [paper] if paper else self.papers():
            d = self.paper_dir(p) / "panels"
            if d.is_dir():
                out += [f"{p}/{f.stem}" for f in sorted(d.glob("*.yaml"))]
        return out

    def resolve_panel_id(self, ref: str) -> str:
        """Accept ``paper/panel`` or a bare panel id when it's unique."""
        ids = self.panel_ids()
        if ref in ids:
            return ref
        hits = [i for i in ids if i.split("/", 1)[1] == ref]
        if len(hits) == 1:
            return hits[0]
        if not hits:
            raise ProjectError(f"no panel {ref!r} (have: {', '.join(ids) or 'none'})")
        raise ProjectError(f"panel {ref!r} is ambiguous: {', '.join(hits)}")

    def panel_path(self, panel_id: str) -> Path:
        paper, panel = panel_id.split("/", 1)
        return self.paper_dir(paper) / "panels" / f"{panel}.yaml"
