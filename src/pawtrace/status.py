"""Project status: the data behind ``pawtrace status`` and its markdown page.

The output is deterministic (no timestamps), so regenerating without changes
gives an identical file.
"""
from __future__ import annotations

from typing import Any

from .panel import Panel
from .project import Project
from .runs import RunStore, last_report
from .spec import Paper

GENERATED = "<!-- generated by `pawtrace status`; do not edit — rerun it instead -->"


def collect(project: Project) -> dict[str, Any]:
    store = RunStore(project.runs_dir)
    modules = project.modules()
    papers = [Paper(p, project.paper_dir(p)).summary() for p in project.papers()]

    panels: list[dict[str, Any]] = []
    for pid in project.panel_ids():
        try:
            title = Panel.load(project, pid).title
        except Exception as exc:  # the runs are still worth showing
            title = str(exc)
        rec = store.latest(pid)
        report = last_report(rec) if rec else None
        failing = (
            [gid for gid, g in (report.get("gates") or {}).items() if g.get("required") and not g.get("pass")]
            if report
            else []
        )
        panels.append(
            {
                "panel": pid,
                "title": title,
                "runs": len(store.list(pid)),
                "latest_run": rec["id"] if rec else None,
                "latest_source": rec.get("source") if rec else None,
                "pass": bool(report["pass"]) if report else None,
                "n_passed": report.get("n_passed") if report else None,
                "n_required": report.get("n_required") if report else None,
                "failing": failing,
            }
        )

    return {
        "project": project.name,
        "profile": project.profile,
        "modules_on": [name for name, on in modules.items() if on],
        "papers": papers,
        "panels": panels,
    }


def _cell(v: Any) -> str:
    s = str(v).replace("\n", " ").replace("|", "\\|")
    return s if s else "—"


def _list(xs: list[str]) -> str:
    return ", ".join(xs) if xs else "—"


def render(project: Project) -> str:
    data = collect(project)
    lines = [GENERATED, "", f"# {data['project']} status", ""]
    lines += [f"Profile: `{data['profile']}` · modules on: {', '.join(data['modules_on']) or 'none'}", ""]

    lines += ["## Papers", ""]
    if data["papers"]:
        lines += [
            "| paper | items | stated/missing/ambiguous | open gaps | adopted deviations | open questions |",
            "|---|---|---|---|---|---|",
        ]
        for p in data["papers"]:
            by = p["items_by_status"]
            sma = f"{by.get('stated', 0)}/{by.get('missing', 0)}/{by.get('ambiguous', 0)}"
            if by.get("contradicted"):
                sma += f" (+{by['contradicted']} contradicted)"
            name = p["paper"] + (f" — {p['title']}" if p.get("title") else "")
            lines.append(
                "| "
                + " | ".join(
                    [
                        _cell(name),
                        _cell(p["items"]),
                        _cell(sma),
                        _cell(_list(p["open_items"])),
                        _cell(_list(p["deviations_adopted"])),
                        _cell(_list(p["open_questions"])),
                    ]
                )
                + " |"
            )
    else:
        lines.append("_No papers._")
    lines.append("")

    lines += ["## Panels", ""]
    if data["panels"]:
        lines += [
            "| panel | title | latest run | verdict | gates | failing gates |",
            "|---|---|---|---|---|---|",
        ]
        for p in data["panels"]:
            verdict = "PASS" if p["pass"] is True else "FAIL" if p["pass"] is False else "—"
            gates = f"{p['n_passed']}/{p['n_required']}" if p["n_required"] is not None else "—"
            latest = f"{p['latest_run']} ({p['latest_source']})" if p["latest_run"] else "—"
            lines.append(
                "| "
                + " | ".join(
                    [
                        _cell(p["panel"]),
                        _cell(p["title"]),
                        _cell(latest),
                        _cell(verdict),
                        _cell(gates),
                        _cell(_list(p["failing"])),
                    ]
                )
                + " |"
            )
    else:
        lines.append("_No panels._")

    return "\n".join(lines) + "\n"
