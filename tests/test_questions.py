# -- lint ----------------------------------------------------------------------


def _write_questions(root, qs):
    led = yaml.safe_load((root / "papers/demo/ledger.yaml").read_text())
    led["questions"] = qs
    (root / "papers/demo/ledger.yaml").write_text(yaml.safe_dump(led, sort_keys=False))


def lint_msgs(capsys, root):
    code, data = jcall(capsys, root, "lint")
    return code, [(p["level"], p["message"]) for p in data["problems"]]


def test_lint_core_errors_even_with_module_off(root, capsys):
    jcall(capsys, root, "modules", "disable", "author-questions")
    _write_questions(root, [
        {"id": "q.a", "question": "x?", "items": ["eq.1"], "status": "pending"},
        {"id": "q.a", "question": "y?", "items": ["no.such.item"]},
        {"id": "q.b", "items": ["eq.1"]},
    ])
    code, msgs = lint_msgs(capsys, root)
    assert code == 1
    assert ("error", "question q.a: status must be one of open, answered-by-us, asked, answered") in msgs
    assert ("error", "duplicate question id q.a") in msgs
    assert ("error", "question q.a: item 'no.such.item' is not in the spec") in msgs
    assert ("error", "question q.b: no question text") in msgs
    assert not any("no why" in m for _, m in msgs)    # module checks stay off


def test_lint_module_checks(root, capsys):
    _write_questions(root, [
        {"id": "q.a", "question": "x?", "items": ["eq.1"], "status": "open"},
        {"id": "q.b", "question": "y?", "items": ["eq.1"], "status": "asked"},
        {"id": "q.c", "question": "z?", "items": ["eq.1"], "status": "answered-by-us"},
        {"id": "q.d", "question": "w?", "panels": ["p9"], "why": "w"},
        {"id": "q.e", "question": "v?", "why": "v"},
        {"id": "q.f", "question": "u?", "panels": ["demo/p1"], "why": "u"},
    ])
    code, msgs = lint_msgs(capsys, root)
    assert ("warn", "question q.a: no why (what the answer would change)") in msgs
    assert ("warn", "question q.b: asked but no asked date") in msgs
    assert ("warn", "question q.c: answered-by-us but no answer recorded") in msgs
    assert any(m.startswith("question q.c: answered-by-us without answer_source") for _, m in msgs)
    assert ("error", "question q.d: panel 'p9' is not a panel of demo") in msgs
    assert ("warn", "question q.e: names no spec items or panels") in msgs
    assert not any("q.f" in m for _, m in msgs)
    assert code == 1


def test_fixture_ledger_lints_clean_for_questions(root, capsys):
    _, msgs = lint_msgs(capsys, root)
    assert [m for _, m in msgs if m.startswith("question")] == []


